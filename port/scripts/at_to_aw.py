#!/usr/bin/env python3
"""Converts a NeoForge accesstransformer.cfg (Mojang names) to a Fabric access widener (named namespace).

Mapping: public/protected -> accessible; '-f' suffix -> additionally mutable (fields) / extendable (methods, classes).
Usage: at_to_aw.py <accesstransformer.cfg> <out.accesswidener>
"""
import re
import sys

lines_out = ["accessWidener v2 official", "# Generated by scripts/at_to_aw.py + resolve_aw_fields.py from upstream accesstransformer.cfg - do not edit by hand.",
             "# Hand-written additions go in the section at the bottom, below the marker line."]
src, dst = sys.argv[1], sys.argv[2]
for raw in open(src, encoding="utf-8"):
    line = raw.split("#", 1)[0].strip()
    if not line:
        continue
    parts = line.split()
    access, cls = parts[0], parts[1].replace(".", "/")
    final_removed = access.endswith("-f")
    if len(parts) == 2:
        lines_out.append(f"accessible class {cls}")
        if final_removed:
            lines_out.append(f"extendable class {cls}")
        continue
    member = parts[2]
    m = re.match(r"^([^(]+)(\(.*)$", member)
    if m:
        name, desc = m.group(1), m.group(2)
        if name == "<init>":
            lines_out.append(f"accessible method {cls} <init> {desc}")
        elif access.startswith("protected"):
            # AT "protected" = callable and overridable by subclasses: AW "extendable" (protected + non-final)
            lines_out.append(f"extendable method {cls} {name} {desc}")
        else:
            lines_out.append(f"accessible method {cls} {name} {desc}")
            if final_removed:
                lines_out.append(f"extendable method {cls} {name} {desc}")
    else:
        # Field: descriptor unknown in AT format; filled in from a lookup table printed as TODO.
        lines_out.append(f"FIELD {cls} {member} {'mutable' if final_removed else ''}".rstrip())
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(lines_out) + "\n")
